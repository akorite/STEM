#!/usr/bin/env node
/**
 * Embed dashboard.html into a PROGMEM header for the ESP32 sketch.
 *
 *   node tools/embed-dashboard.js          # write dashboard_html.h
 *   node tools/embed-dashboard.js --check  # fail if the header is out of date
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const htmlPath = path.join(root, 'dashboard.html');
const headerPath = path.join(root, 'dashboard_html.h');
const delimiter = 'BIOSPHERE';

function buildHeader(html) {
  if (html.includes(`)${delimiter}"`)) {
    throw new Error(`dashboard.html contains the raw-string terminator )${delimiter}"`);
  }
  return `// AUTO-GENERATED by tools/embed-dashboard.js - do not edit by hand.
// Source: dashboard.html
#pragma once

const char INDEX_HTML[] PROGMEM = R"${delimiter}(${html})${delimiter}";
`;
}

const html = fs.readFileSync(htmlPath, 'utf8');
const next = buildHeader(html);
const check = process.argv.includes('--check');

if (check) {
  const current = fs.existsSync(headerPath) ? fs.readFileSync(headerPath, 'utf8') : '';
  if (current !== next) {
    console.error('dashboard_html.h is out of date. Run: npm run embed');
    process.exit(1);
  }
  console.log('dashboard_html.h is in sync with dashboard.html');
} else {
  fs.writeFileSync(headerPath, next, 'utf8');
  console.log(`Wrote ${path.relative(root, headerPath)} (${next.length} bytes)`);
}
