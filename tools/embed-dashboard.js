#!/usr/bin/env node
/**
 * Embed dashboard.html and ota.html into PROGMEM headers for the ESP32 sketch.
 *
 *   node tools/embed-dashboard.js          # write dashboard_html.h
 *   node tools/embed-dashboard.js --check  # fail if the header is out of date
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const dashboardPath = path.join(root, 'dashboard.html');
const otaPath = path.join(root, 'ota.html');
const headerPath = path.join(root, 'dashboard_html.h');
const delimiter = 'BIOSPHERE';

function buildHeader(dashboard, ota) {
  const blocks = [
    ['INDEX_HTML', dashboard, dashboardPath],
    ['OTA_HTML', ota, otaPath]
  ];

  for (const [, html, file] of blocks) {
    if (html.includes(`)${delimiter}"`)) {
      throw new Error(`${path.basename(file)} contains the raw-string terminator )${delimiter}"`);
    }
  }

  return `// AUTO-GENERATED by tools/embed-dashboard.js - do not edit by hand.
// Sources: dashboard.html, ota.html
#pragma once

const char INDEX_HTML[] PROGMEM = R"${delimiter}(${dashboard})${delimiter}";

const char OTA_HTML[] PROGMEM = R"${delimiter}(${ota})${delimiter}";
`;
}

const dashboard = fs.readFileSync(dashboardPath, 'utf8');
const ota = fs.readFileSync(otaPath, 'utf8');
const next = buildHeader(dashboard, ota);
const check = process.argv.includes('--check');

if (check) {
  const current = fs.existsSync(headerPath) ? fs.readFileSync(headerPath, 'utf8') : '';
  if (current !== next) {
    console.error('dashboard_html.h is out of date. Run: npm run embed');
    process.exit(1);
  }
  console.log('dashboard_html.h is in sync with dashboard.html and ota.html');
} else {
  fs.writeFileSync(headerPath, next, 'utf8');
  console.log(`Wrote ${path.relative(root, headerPath)} (${next.length} bytes)`);
}
